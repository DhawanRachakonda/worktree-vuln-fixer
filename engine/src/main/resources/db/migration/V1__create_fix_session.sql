-- Standard SQL only (no engine-specific features, no JSON or array columns), so the store can move to another database later.

-- The valid states live in a table and are enforced by foreign keys, not by CHECK (state IN (...)): H2 2.4.240 builds a constant set
-- for such a check inside the session that creates it (Flyway's) and then fails every later connection with "The database has
-- been closed". A lookup table is standard SQL and does not have that problem.
CREATE TABLE fix_session_state (
    name VARCHAR(20) NOT NULL PRIMARY KEY
);

INSERT INTO fix_session_state (name) VALUES
    ('QUEUED'), ('IN_PROGRESS'), ('DONE'), ('PARTIAL'), ('NEEDS_INPUT'), ('ERROR'), ('INTERRUPTED'), ('REJECTED');

CREATE TABLE fix_session (
    id                VARCHAR(36)   NOT NULL PRIMARY KEY,
    -- arrival order: messages received in the same instant keep their order
    seq               BIGINT        GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    state             VARCHAR(20)   NOT NULL,
    subject           VARCHAR(200)  NOT NULL,
    source            VARCHAR(60)   NOT NULL,
    -- the payload as received (a path, or whatever was sent when the message was rejected), shortened to fit
    report_path       VARCHAR(1024) NOT NULL,
    snapshot_path     VARCHAR(1024),
    repository_path   VARCHAR(1024),
    agent             VARCHAR(100)  NOT NULL,
    runner            VARCHAR(20),
    engine            VARCHAR(20)   NOT NULL,
    received_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    started_at        TIMESTAMP WITH TIME ZONE,
    ended_at          TIMESTAMP WITH TIME ZONE,
    pid               BIGINT,
    pid_started_at    TIMESTAMP WITH TIME ZONE,
    exit_code         INTEGER,
    head_start        VARCHAR(64),
    head_end          VARCHAR(64),
    dirty_at_start    BOOLEAN,
    -- what the agent reported in .appmod/result.json (succeeded, partially_succeeded, needs_input, failed)
    outcome           VARCHAR(30),
    reason            VARCHAR(2000),
    CONSTRAINT fk_fix_session_state FOREIGN KEY (state) REFERENCES fix_session_state (name)
);

CREATE INDEX ix_fix_session_state_seq ON fix_session (state, seq);
CREATE INDEX ix_fix_session_received ON fix_session (received_at);

CREATE TABLE fix_session_event (
    id           BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id   VARCHAR(36)   NOT NULL,
    occurred_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    state        VARCHAR(20)   NOT NULL,
    detail       VARCHAR(2000),
    CONSTRAINT fk_fix_session_event_session FOREIGN KEY (session_id) REFERENCES fix_session (id),
    CONSTRAINT fk_fix_session_event_state FOREIGN KEY (state) REFERENCES fix_session_state (name)
);

CREATE INDEX ix_fix_session_event_session ON fix_session_event (session_id, occurred_at);
